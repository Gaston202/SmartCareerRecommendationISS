def get_booking_tool_manifest() -> List[Dict[str, Any]]:
    """Return OpenAI-compatible tool manifest for booking tools only."""
    manifest: List[Dict[str, Any]] = []
    for tool_fn in BOOKING_TOOLS:
        if isinstance(tool_fn, BaseTool):
            manifest.append(base_tool_to_openai_schema(tool_fn))
        else:
            manifest.append(fn_to_openai_schema(tool_fn))
    return manifest


def find_tool_schema(name: str) -> Optional[Dict[str, Any]]:
    """Find a tool schema by name."""
    for schema in get_tool_manifest():
        if schema.get("function", {}).get("name") == name:
            return schema
    return None


def base_tool_to_openai_schema(tool: BaseTool) -> Dict[str, Any]:
    """Convert a LangChain BaseTool to OpenAI-compatible schema."""
    return {
        "type": "function",
        "function": {
            "name": tool.name,
            "description": tool.description or f"Tool: {tool.name}",
            "parameters": tool.args_schema.schema() if tool.args_schema else {
                "type": "object",
                "properties": {},
            },
        },
    }


def fn_to_openai_schema(fn: Callable) -> Dict[str, Any]:
    """Convert a @tool-decorated function to OpenAI-compatible schema.

    Uses the tool's internal schema (from @tool decorator) if available.
    """
    # Try to get the internal args schema generated by @tool
    schema = getattr(fn, "args_schema", None)
    if schema:
        params = schema.schema() if hasattr(schema, "schema") else dict(schema)
    else:
        params = {"type": "object", "properties": {}}

    description = inspect.getdoc(fn) or f"Tool: {getattr(fn, '__name__', str(fn))}"
    # Clean up docstring: take first paragraph only
    description = description.split("\n\n")[0].strip()

    return {
        "type": "function",
        "function": {
            "name": getattr(fn, "__name__", str(fn)),
            "description": description,
            "parameters": params,
        },
    }


