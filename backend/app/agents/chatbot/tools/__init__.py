_TOOL_MANIFEST: List[Dict[str, Any]] = []


def get_tool_manifest() -> List[Dict[str, Any]]:
    """Return an OpenAI-compatible tool manifest for all chatbot tools.

    Caches the manifest after first call to avoid repeated introspection.
    """
    global _TOOL_MANIFEST
    if _TOOL_MANIFEST:
        return _TOOL_MANIFEST

    manifest: List[Dict[str, Any]] = []
    for tool_fn in ALL_TOOLS:
        if isinstance(tool_fn, BaseTool):
            manifest.append(base_tool_to_openai_schema(tool_fn))
        else:
            manifest.append(fn_to_openai_schema(tool_fn))

    _TOOL_MANIFEST = manifest
    return manifest


def get_tool_descriptions_block() -> str:
    """Return a markdown-formatted list of all tools for prompt injection."""
    lines = ["### Available Tools\n"]
    for tool_fn in ALL_TOOLS:
        if isinstance(tool_fn, BaseTool):
            name = tool_fn.name
            doc = (tool_fn.description or "").strip()
        else:
            name = getattr(tool_fn, "__name__", str(tool_fn))
            doc = inspect.getdoc(tool_fn) or ""
        lines.append(f'- **{name}**: {doc.replace(chr(10), " ")}')
    return "\n".join(lines)


